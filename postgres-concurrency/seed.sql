-- The shop dataset of atomicly's SQL course, without page_views, plus the tables the labs use.
-- The database runs this file when it starts for the first time, and `npm run reset` runs it again.
-- Each lab's test also puts its own rows back to the starting state before it runs.

CREATE TABLE customers (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text NOT NULL,
  email        text UNIQUE,
  city         text,
  signed_up_on date NOT NULL
);

CREATE TABLE products (
  id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     text NOT NULL,
  category text,
  price    numeric(10, 2) NOT NULL CHECK (price >= 0),
  stock    integer NOT NULL DEFAULT 0
);

CREATE TABLE orders (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers (id),
  status      text NOT NULL CHECK (status IN ('pending', 'paid', 'shipped', 'cancelled')),
  ordered_on  date NOT NULL,
  shipped_on  date
);

CREATE TABLE order_items (
  order_id   integer NOT NULL REFERENCES orders (id),
  product_id integer NOT NULL REFERENCES products (id),
  quantity   integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(10, 2) NOT NULL,
  PRIMARY KEY (order_id, product_id)
);

CREATE TABLE employees (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  manager_id integer REFERENCES employees (id),
  department text NOT NULL,
  salary     integer NOT NULL
);

-- Store credit: each customer can send part of their balance to another customer (lab 03).
CREATE TABLE accounts (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL UNIQUE REFERENCES customers (id),
  balance     numeric(10, 2) NOT NULL
);

-- Background work, such as sending an order's receipt. A worker takes a queued job, does the work,
-- and marks it done. job_runs gets a row each time a worker does a job's work (lab 02).
CREATE TABLE jobs (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind       text NOT NULL,
  order_id   integer NOT NULL REFERENCES orders (id),
  status     text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'done')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE job_runs (
  job_id integer NOT NULL REFERENCES jobs (id),
  worker text NOT NULL,
  ran_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- A coupon works for at most max_uses orders (lab 04).
CREATE TABLE coupons (
  code        text PRIMARY KEY,
  percent_off integer NOT NULL CHECK (percent_off BETWEEN 1 AND 100),
  max_uses    integer NOT NULL
);

CREATE TABLE coupon_redemptions (
  coupon_code text NOT NULL REFERENCES coupons (code),
  order_id    integer NOT NULL REFERENCES orders (id),
  PRIMARY KEY (coupon_code, order_id)
);

