-- The shop dataset of atomicly's SQL course: customers, products, orders, and order items.
-- The database runs this file when it starts for the first time, and `npm run reset` runs it again.

CREATE TABLE customers (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text NOT NULL,
  email        text UNIQUE,
  city         text,
  signed_up_on date NOT NULL
);

CREATE TABLE products (
  id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     text NOT NULL,
  category text,
  price    numeric(10, 2) NOT NULL CHECK (price >= 0),
  stock    integer NOT NULL DEFAULT 0
);

CREATE TABLE orders (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers (id),
  status      text NOT NULL CHECK (status IN ('pending', 'paid', 'shipped', 'cancelled')),
  ordered_on  date NOT NULL,
  shipped_on  date
);

CREATE TABLE order_items (
  order_id   integer NOT NULL REFERENCES orders (id),
  product_id integer NOT NULL REFERENCES products (id),
  quantity   integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(10, 2) NOT NULL,
  PRIMARY KEY (order_id, product_id)
);

-- The orders of the customer the app is serving (lab 03). The app puts the customer's id in the
-- session setting app.customer_id, and the view reads it. Apps use the same setting for row-level
-- security policies. With no customer set, the view returns no rows.
CREATE VIEW my_orders AS
SELECT *
FROM orders
WHERE customer_id = NULLIF(current_setting('app.customer_id', true), '')::integer;

