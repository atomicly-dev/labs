-- The shop dataset of atomicly's SQL course, at the size of a real shop: 50,000 customers, 500
-- products, 300,000 orders, and 600,000 order items. generate_series makes the rows, and plain
-- arithmetic on the row number picks each value, so every seed has the same data.
-- The database runs this file when it starts for the first time, and `npm run reset` runs it again.

-- Query statistics for lab 01. The server loads the library at start (see compose.yaml).
CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

CREATE TABLE customers (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text NOT NULL,
  email        text UNIQUE,
  city         text,
  signed_up_on date NOT NULL
);

CREATE TABLE products (
  id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     text NOT NULL,
  category text,
  price    numeric(10, 2) NOT NULL CHECK (price >= 0),
  stock    integer NOT NULL DEFAULT 0
);

-- The foreign keys come after the rows, because checking them all at once is faster than one
-- row at a time.
CREATE TABLE orders (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id       integer NOT NULL,
  status            text NOT NULL CHECK (status IN ('pending', 'paid', 'shipped', 'cancelled')),
  ordered_on        date NOT NULL,
  shipped_on        date,
  -- Lab 03: what the payment provider's webhooks say about the order's payment, and the time of
  -- the event that said it.
  payment_status    text CHECK (payment_status IN ('paid', 'refunded')),
  payment_status_at timestamptz
);

CREATE TABLE order_items (
  order_id   integer NOT NULL,
  product_id integer NOT NULL,
  quantity   integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(10, 2) NOT NULL,
  PRIMARY KEY (order_id, product_id)
);

-- Lab 03: each webhook event the shop has handled, by the provider's event id.
CREATE TABLE webhook_events (
  id          text PRIMARY KEY,
  received_at timestamptz NOT NULL DEFAULT now()
);

-- Lab 03: the shop's payment ledger, one row per money movement. A refund has a negative amount.
CREATE TABLE payments (
  id       integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders (id),
  amount   numeric(10, 2) NOT NULL,
  event_id text NOT NULL
);

