-- The shop's orders, as they were before last night's base backup: 1,200 orders from the last
-- 8 days. Production runs this file when it starts for the first time, and each lab's test runs
-- it again before it takes the base backup, so every run starts from the same rows.

DROP TABLE IF EXISTS orders;

CREATE TABLE orders (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL,
  total       numeric(10, 2) NOT NULL CHECK (total > 0),
  ordered_at  timestamptz NOT NULL DEFAULT now()
);

INSERT INTO orders (customer_id, total, ordered_at)
SELECT 1 + (i * 37) % 400,
       5 + (i * 7919) % 25000 / 100.0,
       now() - (1201 - i) * interval '10 minutes'
FROM generate_series(1, 1200) AS i;
